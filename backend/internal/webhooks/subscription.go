// The events a subscription can listen to. They are stable identifiers.
const (
	EventNoteCreated  = "note.created"
	EventNoteUpdated  = "note.updated"
	EventNoteDeleted  = "note.deleted"
	EventNoteRenamed  = "note.renamed"
	EventNoteMoved    = "note.moved"
	EventNoteRestored = "note.restored"
)

// knownEvents is the set of the events a subscription can listen to.
var knownEvents = map[string]bool{
	EventNoteCreated:  true,
	EventNoteUpdated:  true,
	EventNoteDeleted:  true,
	EventNoteRenamed:  true,
	EventNoteMoved:    true,
	EventNoteRestored: true,
}

// KnownEvents returns the sorted list of the events.
func KnownEvents() []string {
	out := make([]string, 0, len(knownEvents))
	for e := range knownEvents {
		out = append(out, e)
	}
	sort.Strings(out)
	return out
}

// Subscription is the registration of a URL for a set of events.
type Subscription struct {
	// ID is the stable identifier of the subscription.
	ID string `json:"id"`
	// Owner is the name of the user that registered the subscription.
	Owner string `json:"owner"`
	// URL is the address the events are posted to.
	URL string `json:"url"`
	// Events is the list of the events the subscription listens to.
	Events []string `json:"events"`
	// Secret is the shared secret of the signature. It is only returned by
	// the creation of a subscription: every other answer carries an empty
	// secret.
	Secret string `json:"secret,omitempty"`
	// CreatedAt is the creation time of the subscription.
	CreatedAt time.Time `json:"createdAt"`
}

// Matches reports whether the subscription listens to the event.
func (s Subscription) Matches(event string) bool {
	if len(s.Events) == 0 {
		return true
	}
	for _, e := range s.Events {
		if e == event {
			return true
		}
	}
	return false
}

// ValidateURL checks the address of a subscription.
//
// The guard against the server side request forgery: only HTTPS is allowed,
// and a plain HTTP request is only allowed when it goes to the loopback
// interface. A subscription that points to a private network of the machine
// (or to a metadata service of a cloud provider) is refused.
func ValidateURL(raw string) error {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return newError(ErrInvalid, "the url of the subscription is required")
	}
	u, err := url.Parse(raw)
	if err != nil {
		return newError(ErrInvalid, "the url of the subscription is not valid")
	}
	if u.User != nil {
		return newError(ErrInvalid, "the url of the subscription must not carry credentials")
	}
	switch strings.ToLower(u.Scheme) {
	case "https":
		if u.Hostname() == "" {
			return newError(ErrInvalid, "the url of the subscription is not valid")
		}
		return nil
	case "http":
		host := u.Hostname()
		if host == "" {
			return newError(ErrInvalid, "the url of the subscription is not valid")
		}
		if isLoopbackHost(host) {
			return nil
		}
		return newError(ErrInvalid, "the url of the subscription must use https, "+
			"except for a loopback address")
	default:
		return newError(ErrInvalid, "the url of the subscription must use https, "+
			"except for a loopback address")
	}
}

// isLoopbackHost reports whether the host is a loopback address.
func isLoopbackHost(host string) bool {
	host = strings.ToLower(strings.Trim(host, "[]"))
	if host == "localhost" {
		return true
	}
	ip := net.ParseIP(host)
	return ip != nil && ip.IsLoopback()
}

// ValidateEvents checks the list of the events of a subscription. An empty
// list means every event.
func ValidateEvents(events []string) ([]string, error) {
	if len(events) == 0 {
		return nil, nil
	}
	out := make([]string, 0, len(events))
	for _, e := range events {
		e = strings.TrimSpace(e)
		if e == "" {
			continue
		}
		if !knownEvents[e] {
			return nil, newError(ErrInvalid, fmt.Sprintf("the event %q is unknown", e))
		}
		if !containsString(out, e) {
			out = append(out, e)
		}
	}
	sort.Strings(out)
	return out, nil
}

// containsString reports whether the list holds the value.
func containsString(list []string, value string) bool {
	for _, v := range list {
		if v == value {
			return true
		}
	}
	return false
}

// Create registers a subscription and returns it with its secret. The secret
// is generated by the server: the user never chooses it.
func (s *Store) Create(ctx context.Context, owner, rawURL string, events []string) (Subscription, error) {
	if err := ValidateURL(rawURL); err != nil {
		return Subscription{}, err
	}
	evs, err := ValidateEvents(events)
	if err != nil {
		return Subscription{}, err
	}
	secret, err := randomSecret()
	if err != nil {
		return Subscription{}, err
	}
	id, err := randomID()
	if err != nil {
		return Subscription{}, err
	}
	encoded, err := json.Marshal(evs)
	if err != nil {
		return Subscription{}, fmt.Errorf("webhooks: cannot encode the events: %w", err)
	}
	created := now()
	_, err = s.db.ExecContext(ctx,
		`INSERT INTO subscriptions (id, owner, url, events, secret, created_at) VALUES (?, ?, ?, ?, ?, ?)`,
		id, owner, strings.TrimSpace(rawURL), string(encoded), secret, created.UnixMilli())
	if err != nil {
		return Subscription{}, fmt.Errorf("webhooks: cannot create the subscription: %w", err)
	}
	return Subscription{
		ID:        id,
		Owner:     owner,
		URL:       strings.TrimSpace(rawURL),
		Events:    evs,
		Secret:    secret,
		CreatedAt: created,
	}, nil
}

// Subscriptions returns the subscriptions of a user. When all is true the
// subscriptions of every user are returned; only an administrator may ask
// for them.
//
// The secret is never part of the answer.
func (s *Store) Subscriptions(ctx context.Context, owner string, all bool) ([]Subscription, error) {
	query := `SELECT id, owner, url, events, secret, created_at FROM subscriptions`
	args := []any{}
	if !all {
		query += ` WHERE owner = ?`
		args = append(args, owner)
	}
	query += ` ORDER BY created_at, id`
	rows, err := s.db.QueryContext(ctx, query, args...)
	if err != nil {
		return nil, fmt.Errorf("webhooks: cannot list the subscriptions: %w", err)
	}
	defer rows.Close()
	out := []Subscription{}
	for rows.Next() {
		sub, err := scanSubscription(rows)
		if err != nil {
			return nil, err
		}
		// The secret never leaves the store, except through the method
		// Secret, which is used by the delivery worker.
		sub.Secret = ""
		out = append(out, sub)
	}
	return out, rows.Err()
}

// Subscription returns the subscription with the given identifier. The secret
// is not part of the answer.
func (s *Store) Subscription(ctx context.Context, id string) (Subscription, error) {
	row := s.db.QueryRowContext(ctx,
		`SELECT id, owner, url, events, secret, created_at FROM subscriptions WHERE id = ?`, id)
	sub, err := scanSubscription(row)
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return Subscription{}, newError(ErrNotFound, "the subscription does not exist")
		}
		return Subscription{}, err
	}
	// The secret never leaves the store, except through the method Secret.
	sub.Secret = ""
	return sub, nil
}

// Secret returns the shared secret of a subscription. It is used by the
// delivery worker to sign the body of a request.
func (s *Store) Secret(ctx context.Context, id string) (string, error) {
	var secret string
	err := s.db.QueryRowContext(ctx, `SELECT secret FROM subscriptions WHERE id = ?`, id).Scan(&secret)
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return "", newError(ErrNotFound, "the subscription does not exist")
		}
		return "", fmt.Errorf("webhooks: cannot read the secret: %w", err)
	}
	return secret, nil
}

// DeleteSubscription removes a subscription and the deliveries that wait for
// it.
func (s *Store) DeleteSubscription(ctx context.Context, id string) error {
	res, err := s.db.ExecContext(ctx, `DELETE FROM subscriptions WHERE id = ?`, id)
	if err != nil {
		return fmt.Errorf("webhooks: cannot remove the subscription: %w", err)
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return newError(ErrNotFound, "the subscription does not exist")
	}
	if _, err := s.db.ExecContext(ctx,
		`DELETE FROM outbox WHERE subscription_id = ? AND state = 'pending'`, id); err != nil {
		return fmt.Errorf("webhooks: cannot remove the deliveries of the subscription: %w", err)
	}
	return nil
}

// scanner reads the columns of a subscription.
type scanner interface {
	Scan(dest ...any) error
}

// scanSubscription reads a subscription from a row.
func scanSubscription(row scanner) (Subscription, error) {
	var id, owner, rawURL, encoded, secret string
	var created int64
	if err := row.Scan(&id, &owner, &rawURL, &encoded, &secret, &created); err != nil {
		return Subscription{}, err
	}
	var events []string
	if encoded != "" {
		if err := json.Unmarshal([]byte(encoded), &events); err != nil {
			return Subscription{}, fmt.Errorf("webhooks: cannot decode the events: %w", err)
		}
	}
	if events == nil {
		events = []string{}
	}
	return Subscription{
		ID:        id,
		Owner:     owner,
		URL:       rawURL,
		Events:    events,
		Secret:    secret,
		CreatedAt: time.UnixMilli(created).UTC(),
	}, nil
}

// randomID returns a random identifier of a subscription.
func randomID() (string, error) {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return "", fmt.Errorf("webhooks: cannot read the identifier: %w", err)
	}
	return hex.EncodeToString(b), nil
}

// randomSecret returns a random shared secret of a subscription.
func randomSecret() (string, error) {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		return "", fmt.Errorf("webhooks: cannot read the secret: %w", err)
	}
	return hex.EncodeToString(b), nil
}
